"""Open a draft GitHub PR for AppLogic remediations (never auto-merged)."""

from __future__ import annotations

import json
import logging
import os
import subprocess
import tempfile
from pathlib import Path
from typing import Any

logger = logging.getLogger(__name__)


def open_draft_pr(plan_row: dict[str, Any]) -> dict[str, Any]:
    """
    Creates a local branch + draft PR via `gh` when GH_TOKEN/gh is available.
    Writes a sandbox file under remediation-sandbox/ so CI has something to build.
    """
    if os.getenv("CAUSA_GITHUB_PR_ENABLED", "1") in ("0", "false", "False"):
        return {"attempted": False, "reason": "CAUSA_GITHUB_PR_ENABLED=0"}

    details = plan_row.get("details") or {}
    nim_patch = details.get("nim_patch") if isinstance(details, dict) else None
    node = str(plan_row.get("candidate_node") or "service")
    incident = str(plan_row.get("incident_id") or "unknown")
    branch = f"causa/fix-{node}-{incident[:12]}".replace("/", "-")

    title = f"fix({node}): proposed remediation from Causa RCA"
    body = f"## Causa Dev C\n\nIncident `{incident}`\n\nDraft only — never auto-merged.\n"
    diff_text = (
        f"# proposed guard for {node}\n"
        f"# incident: {incident}\n"
        "raise_timeout_ms = 2000\n"
        "retry_budget = 2\n"
    )
    if isinstance(nim_patch, dict):
        title = str(nim_patch.get("title") or title)
        body = str(nim_patch.get("body") or body)
        if nim_patch.get("diff"):
            diff_text = str(nim_patch["diff"])

    repo_root = Path(__file__).resolve().parents[3]
    sandbox = repo_root / "remediation-sandbox"
    sandbox.mkdir(parents=True, exist_ok=True)
    target = sandbox / f"{node}_fix.py"
    target.write_text(
        '"""Draft remediation sandbox file — generated by Causa Dev C."""\n'
        f"INCIDENT = {incident!r}\n"
        f"NODE = {node!r}\n"
        f"NOTES = {diff_text!r}\n",
        encoding="utf-8",
    )

    # Prefer gh; if unavailable, return payload-only success for UI.
    gh = _which("gh")
    if not gh:
        return {
            "attempted": True,
            "mode": "pr_payload_only",
            "status": "succeeded",
            "pr": {
                "title": title,
                "body": body,
                "head": branch,
                "draft": True,
                "merged": False,
                "url": None,
                "file": str(target.relative_to(repo_root)),
            },
        }

    # Non-destructive: do not auto-commit unless CAUSA_GITHUB_AUTOCOMMIT=1
    if os.getenv("CAUSA_GITHUB_AUTOCOMMIT", "0") not in ("1", "true", "True"):
        return {
            "attempted": True,
            "mode": "pr_payload_prepared",
            "status": "succeeded",
            "pr": {
                "title": title,
                "body": body,
                "head": branch,
                "draft": True,
                "merged": False,
                "url": None,
                "file": str(target.relative_to(repo_root)),
                "note": "Set CAUSA_GITHUB_AUTOCOMMIT=1 to create branch/PR via gh",
            },
        }

    try:
        subprocess.run(["git", "checkout", "-B", branch], cwd=repo_root, check=False, capture_output=True)
        subprocess.run(["git", "add", str(target)], cwd=repo_root, check=False, capture_output=True)
        subprocess.run(
            ["git", "commit", "-m", title[:72]],
            cwd=repo_root,
            check=False,
            capture_output=True,
        )
        subprocess.run(["git", "push", "-u", "origin", branch], cwd=repo_root, check=False, capture_output=True)
        proc = subprocess.run(
            [
                "gh",
                "pr",
                "create",
                "--draft",
                "--title",
                title,
                "--body",
                body,
                "--head",
                branch,
            ],
            cwd=repo_root,
            capture_output=True,
            text=True,
            check=False,
        )
        url = (proc.stdout or "").strip() or None
        return {
            "attempted": True,
            "mode": "github_draft_pr",
            "status": "succeeded" if proc.returncode == 0 else "failed",
            "pr": {
                "title": title,
                "body": body,
                "head": branch,
                "draft": True,
                "merged": False,
                "url": url,
                "file": str(target.relative_to(repo_root)),
            },
            "stderr": (proc.stderr or "")[:400],
        }
    except Exception as exc:  # noqa: BLE001
        return {"attempted": True, "mode": "github_draft_pr", "status": "failed", "error": str(exc)}


def _which(name: str) -> str | None:
    from shutil import which

    return which(name)
